// ---------- Web Crypto helpers (replace Node's "crypto" module) ----------

function bufToHex(buf) {
  return [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

function randomHex(byteLength) {
  const arr = new Uint8Array(byteLength);
  crypto.getRandomValues(arr);
  return bufToHex(arr.buffer);
}

async function sha256Hex(value) {
  const data = new TextEncoder().encode(String(value || ''));
  const digest = await crypto.subtle.digest('SHA-256', data);
  return bufToHex(digest);
}

function token() {
  return randomHex(32); // 64 hex chars, same shape as the old crypto.randomBytes(32).toString('hex')
}

function randomCode6() {
  const arr = new Uint32Array(1);
  crypto.getRandomValues(arr);
  return String(arr[0] % 1000000).padStart(6, '0');
}

// ---------- Base64 <-> bytes (Workers have no Buffer by default for this) ----------

function base64ToBytes(b64) {
  const bin = atob(String(b64 || '').replace(/^data:[^,]*,/, '').replace(/\s+/g, ''));
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}
function bytesToBase64(bytes) {
  let bin = '';
  for (let i = 0; i < bytes.length; i++) bin += String.fromCharCode(bytes[i]);
  return btoa(bin);
}
function textToBase64(text) {
  return bytesToBase64(new TextEncoder().encode(text));
}

// ---------- PNG helpers (read width/height without an image library) ----------
// PNG layout: 8-byte signature, then a 4-byte length + "IHDR" + width(4) + height(4) (big-endian).

function pngDimensions(bytes) {
  if (bytes.length < 24) return null;
  const sig = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  for (let i = 0; i < 8; i++) if (bytes[i] !== sig[i]) return null;
  if (bytes[12] !== 0x49 || bytes[13] !== 0x48 || bytes[14] !== 0x44 || bytes[15] !== 0x52) return null; // "IHDR"
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  return { width: view.getUint32(16, false), height: view.getUint32(20, false) };
}

// ---------- RSA signing for Yggdrasil texture properties (authlib-injector) ----------
// The private key is a PKCS8 PEM stored in the RSA_PRIVATE_KEY secret; the matching
// SPKI PEM public key is stored in RSA_PUBLIC_KEY (see README-SKINS.md for how to
// generate this pair — it is NOT auto-generated by the Worker).

function pemToDer(pem) {
  const b64 = String(pem || '')
    .replace(/-----BEGIN [^-]+-----/g, '')
    .replace(/-----END [^-]+-----/g, '')
    .replace(/\s+/g, '');
  return base64ToBytes(b64);
}
let _rsaPrivateKeyPromise = null;
function getRsaPrivateKey(env) {
  if (!_rsaPrivateKeyPromise) {
    const der = pemToDer(env.RSA_PRIVATE_KEY);
    _rsaPrivateKeyPromise = crypto.subtle.importKey(
      'pkcs8', der.buffer, { name: 'RSASSA-PKCS1-v1_5', hash: 'SHA-1' }, false, ['sign']
    );
  }
  return _rsaPrivateKeyPromise;
}
async function rsaSignBase64(env, valueUtf8) {
  const key = await getRsaPrivateKey(env);
  const sig = await crypto.subtle.sign('RSASSA-PKCS1-v1_5', key, new TextEncoder().encode(valueUtf8));
  return bytesToBase64(new Uint8Array(sig));
}

// ---------- MD5 + оффлайн-UUID игрока ----------
// Ровно тот же алгоритм, что и offlineUuid(nick) в лаунчере (main.js):
// UUID v3 из MD5("OfflinePlayer:<ник>") — стандартный способ Minecraft
// генерировать UUID в оффлайн-режиме. Вычисляя его тут же на сервере (а не
// присваивая случайный), сайт и игра всегда ссылаются на один и тот же
// профиль/скин без какой-либо синхронизации UUID между ними.
function md5(bytes) {
  const s = [
    7,12,17,22, 7,12,17,22, 7,12,17,22, 7,12,17,22,
    5, 9,14,20, 5, 9,14,20, 5, 9,14,20, 5, 9,14,20,
    4,11,16,23, 4,11,16,23, 4,11,16,23, 4,11,16,23,
    6,10,15,21, 6,10,15,21, 6,10,15,21, 6,10,15,21
  ];
  const K = new Uint32Array(64);
  for (let i = 0; i < 64; i++) K[i] = Math.floor(Math.abs(Math.sin(i + 1)) * 4294967296) >>> 0;
  let a0 = 0x67452301, b0 = 0xefcdab89, c0 = 0x98badcfe, d0 = 0x10325476;
  const msgLen = bytes.length;
  const totalLen = (Math.floor((msgLen + 8) / 64) + 1) * 64;
  const padded = new Uint8Array(totalLen);
  padded.set(bytes);
  padded[msgLen] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(totalLen - 8, (msgLen * 8) >>> 0, true);
  view.setUint32(totalLen - 4, Math.floor((msgLen * 8) / 4294967296) >>> 0, true);
  const rotl = (x, c) => (x << c) | (x >>> (32 - c));
  for (let chunkStart = 0; chunkStart < totalLen; chunkStart += 64) {
    const M = new Uint32Array(16);
    for (let j = 0; j < 16; j++) M[j] = view.getUint32(chunkStart + j * 4, true);
    let A = a0, B = b0, C = c0, D = d0;
    for (let i = 0; i < 64; i++) {
      let F, g;
      if (i < 16) { F = (B & C) | (~B & D); g = i; }
      else if (i < 32) { F = (D & B) | (~D & C); g = (5 * i + 1) % 16; }
      else if (i < 48) { F = B ^ C ^ D; g = (3 * i + 5) % 16; }
      else { F = C ^ (B | ~D); g = (7 * i) % 16; }
      F = (F + A + K[i] + M[g]) >>> 0;
      A = D; D = C; C = B;
      B = (B + rotl(F, s[i])) >>> 0;
    }
    a0 = (a0 + A) >>> 0; b0 = (b0 + B) >>> 0; c0 = (c0 + C) >>> 0; d0 = (d0 + D) >>> 0;
  }
  const out = new Uint8Array(16);
  const outView = new DataView(out.buffer);
  outView.setUint32(0, a0, true); outView.setUint32(4, b0, true);
  outView.setUint32(8, c0, true); outView.setUint32(12, d0, true);
  return out;
}
function offlineUuidForNick(nick) {
  const digest = md5(new TextEncoder().encode(`OfflinePlayer:${nick}`));
  digest[6] = (digest[6] & 0x0f) | 0x30;
  digest[8] = (digest[8] & 0x3f) | 0x80;
  const hex = [...digest].map((b) => b.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

// ---------- Small request/response helpers (replace Node's "http") ----------

const ALLOWED_ORIGINS = new Set([
  'https://spaceclientbeta.github.io',
  'https://spaceclientbeta.layero.app',
  'https://space-client.layero.app',
  'http://localhost:3000',
  'http://127.0.0.1:3000'
]);

function isAllowedOrigin(origin) {
  if (!origin) return false;
  if (ALLOWED_ORIGINS.has(origin)) return true;
  try {
    const u = new URL(origin);
    return u.protocol === 'https:' && u.hostname.endsWith('.github.io');
  } catch {
    return false;
  }
}

function corsHeaders(request) {
  const origin = request.headers.get('Origin') || '';
  const headers = new Headers({
    'Access-Control-Allow-Headers': 'Content-Type, Authorization',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    Vary: 'Origin'
  });
  if (isAllowedOrigin(origin)) {
    headers.set('Access-Control-Allow-Origin', origin);
    headers.set('Access-Control-Allow-Credentials', 'true');
  }
  return headers;
}

function json(request, status, body, extraHeaders) {
  const headers = corsHeaders(request);
  headers.set('Content-Type', 'application/json; charset=utf-8');
  headers.set('Cache-Control', 'no-store');
  if (extraHeaders) for (const [k, v] of Object.entries(extraHeaders)) headers.append(k, v);
  return new Response(JSON.stringify(body), { status, headers });
}

async function readBody(request) {
  const text = await request.text();
  if (!text) return {};
  if (text.length > 1024 * 1024) throw new Error('Слишком большой запрос.');
  try {
    return JSON.parse(text);
  } catch {
    throw new Error('Некорректный JSON.');
  }
}

function getClientIp(request) {
  return (
    request.headers.get('cf-connecting-ip') ||
    String(request.headers.get('x-forwarded-for') || '').split(',')[0].trim() ||
    'unknown'
  );
}

function getClientDevice(userAgent, body = {}) {
  const ua = String(userAgent || '');
  const requested = String(body.deviceLabel || '').trim();
  const allowed = ['Windows 10', 'Windows 11', 'Windows', 'Android', 'Linux', 'Linux (Ubuntu)', 'Linux (Mint)'];
  if (allowed.includes(requested)) return requested;
  if (/Android/i.test(ua)) return 'Android';
  if (/Windows/i.test(ua)) return 'Windows';
  if (/Linux/i.test(ua)) {
    if (/Ubuntu/i.test(ua)) return 'Linux (Ubuntu)';
    if (/Linux Mint|Mint/i.test(ua)) return 'Linux (Mint)';
    return 'Linux';
  }
  return 'Неизвестное устройство';
}

function getClientMeta(request, body = {}) {
  const width = Number(body.screenWidth);
  const height = Number(body.screenHeight);
  const dpr = Number(body.devicePixelRatio);
  return {
    ip: getClientIp(request),
    user_agent: String(request.headers.get('user-agent') || '').slice(0, 500),
    device: getClientDevice(request.headers.get('user-agent'), body),
    screen_width: Number.isInteger(width) && width > 0 && width <= 10000 ? width : null,
    screen_height: Number.isInteger(height) && height > 0 && height <= 10000 ? height : null,
    screen_dpr: Number.isFinite(dpr) && dpr > 0 && dpr <= 10 ? Math.round(dpr * 100) / 100 : null
  };
}

function getCookie(request, name) {
  const raw = request.headers.get('cookie') || '';
  const found = raw.split(';').map((x) => x.trim()).find((x) => x.startsWith(name + '='));
  return found ? decodeURIComponent(found.slice(name.length + 1)) : '';
}

function setCookieHeader(name, value, maxAge, isProd) {
  const secure = isProd ? '; Secure' : '';
  return `${name}=${encodeURIComponent(value)}; Max-Age=${maxAge}; Path=/; HttpOnly; SameSite=${isProd ? 'None' : 'Lax'}${secure}`;
}

function clearCookieHeader(name) {
  return `${name}=; Max-Age=0; Path=/; HttpOnly; SameSite=Lax`;
}

function authToken(request) {
  const value = request.headers.get('authorization') || '';
  return value.startsWith('Bearer ') ? value.slice(7).trim() : '';
}

// ---------- Domain helpers ----------

function normalizeNick(value) {
  return String(value || '').trim().toLowerCase();
}
function validNick(value) {
  return /^[A-Za-zА-Яа-яЁё0-9_ .-]{3,24}$/.test(String(value || '').trim());
}
function validEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(value || '').trim());
}

function safeUser(row) {
  if (!row) return null;
  return {
    email: row.email,
    nick: row.nick,
    balance: Number(row.balance || 0),
    banned: !!row.banned,
    plan: row.plan || null,
    isAdmin: undefined, // set by caller (needs ADMIN_NICK from env)
    expires: row.expires == null ? null : new Date(row.expires).getTime(),
    registeredAt: row.registered_at ? new Date(row.registered_at).getTime() : null,
    lastSeen: row.last_seen ? new Date(row.last_seen).getTime() : null,
    isOnline: !!row.is_online,
    lastIp: row.last_ip || null,
    lastDevice: row.last_device || getClientDevice(row.last_user_agent),
    lastUserAgent: row.last_user_agent || null,
    screenWidth: row.last_screen_width == null ? null : Number(row.last_screen_width),
    screenHeight: row.last_screen_height == null ? null : Number(row.last_screen_height),
    screenDpr: row.last_screen_dpr == null ? null : Number(row.last_screen_dpr),
    bio: row.bio || '',
    playtimeSeconds: Number(row.playtime_seconds || 0),
    uuid: row.uuid || null
  };
}

function friendOnline(lastSeen, isOnline = null) {
  if (!lastSeen) return false;
  const fresh = Date.now() - new Date(lastSeen).getTime() < 12000;
  return isOnline === false ? false : fresh && (isOnline === true || isOnline == null);
}
function publicFriend(row) {
  return {
    email: row.email,
    nick: row.nick,
    lastSeen: row.last_seen ? new Date(row.last_seen).getTime() : null,
    online: friendOnline(row.last_seen, row.is_online)
  };
}

