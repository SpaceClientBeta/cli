export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const pathname = url.pathname;

    if (request.method === 'OPTIONS') {
      return new Response(null, { status: 204, headers: corsHeaders(request) });
    }

    // /api/friends/messages?friendEmail=... (GET) has a query string.
    if (request.method === 'GET' && pathname === '/api/friends/messages') {
      const app = new App(env, request);
      try {
        await app.auditLog(auditActionName(pathname, request.method));
        return await handleFriendMessages(app, request);
      } catch (err) {
        console.error(err);
        return json(request, 500, { message: 'Внутренняя ошибка сервера.' });
      }
    }

    if (pathname === '/api/music' && request.method === 'GET') {
      const app = new App(env, request);
      return handleMusic(app, request, env);
    }

    // Корень Yggdrasil-сервера (authlib-injector сначала запрашивает его,
    // чтобы узнать публичный ключ и разрешённые домены текстур).
    if (request.method === 'GET' && (pathname === '/yggdrasil' || pathname === '/yggdrasil/')) {
      const app = new App(env, request);
      return handleYggRoot(app, request, env);
    }

    // GET /yggdrasil/sessionserver/session/minecraft/profile/<uuid> — вызывает сам
    // Minecraft-клиент, чтобы получить (подписанные) текстуры игрока по UUID.
    if (request.method === 'GET' && pathname.startsWith('/yggdrasil/sessionserver/session/minecraft/profile/')) {
      const app = new App(env, request);
      const uuidParam = pathname.slice('/yggdrasil/sessionserver/session/minecraft/profile/'.length);
      try {
        await app.auditLog('Игровой запрос профиля/скина');
        return await handleYggProfile(app, request, uuidParam, env);
      } catch (err) {
        console.error(err);
        return json(request, 500, { message: 'Внутренняя ошибка сервера.' });
      }
    }

    // Публичные PNG скина/плаща: /textures/skin/<uuid>.png, /textures/cape/<uuid>.png
    if (request.method === 'GET' && (pathname.startsWith('/textures/skin/') || pathname.startsWith('/textures/cape/'))) {
      const app = new App(env, request);
      const kind = pathname.startsWith('/textures/skin/') ? 'skin' : 'cape';
      const uuidWithExt = pathname.slice(`/textures/${kind}/`.length);
      try {
        return await handleTextureImage(app, request, kind, uuidWithExt);
      } catch (err) {
        console.error(err);
        return new Response('Internal error', { status: 500 });
      }
    }

    const match = ROUTES.find(([method, path]) => method === request.method && path === pathname);
    if (match) {
      const app = new App(env, request);
      try {
        if (pathname !== '/api/admin/logs') {
          await app.auditLog(auditActionName(pathname, request.method));
        }
        return await match[2](app, request);
      } catch (err) {
        console.error(err);
        return json(request, 500, { message: 'Внутренняя ошибка сервера.' });
      }
    }

    // Not an API route: let the [assets] binding serve the static site
    // (index.html, style.css, script.js, ...), including its SPA fallback.
    if (request.method === 'GET' || request.method === 'HEAD') {
      return env.ASSETS.fetch(request);
    }

    return json(request, 405, { message: 'Метод не поддерживается.' });
  }
};
