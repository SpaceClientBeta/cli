async function handleSkinsUpload(app, request) {
  if (!app.requireSupabase()) return json(request, 503, { message: 'Supabase не настроен.' });
  const account = await app.requireUser();
  if (!account) return json(request, 401, { message: 'Сессия истекла.' });
  const body = await readBody(request);
  const type = body.type === 'cape' ? 'cape' : body.type === 'skin' ? 'skin' : null;
  if (!type) return json(request, 400, { message: 'Некорректный тип текстуры.' });
  const model = body.model === 'slim' ? 'slim' : 'classic';
  let bytes;
  try {
    bytes = base64ToBytes(body.imageBase64);
  } catch {
    return json(request, 400, { message: 'Некорректный файл изображения.' });
  }
  if (!bytes.length || bytes.length > 400 * 1024) return json(request, 400, { message: 'Файл должен быть PNG размером до 400 КБ.' });
  const dim = pngDimensions(bytes);
  if (!dim) return json(request, 400, { message: 'Файл должен быть в формате PNG.' });
  const okSkin = type === 'skin' && dim.width === 64 && (dim.height === 64 || dim.height === 32);
  const okCape = type === 'cape' && dim.width === 64 && dim.height === 32;
  if (!okSkin && !okCape) {
    return json(request, 400, {
      message: type === 'skin' ? 'Скин должен быть PNG размером 64×64 (или 64×32).' : 'Плащ должен быть PNG размером 64×32.'
    });
  }
  const clean = bytesToBase64(bytes);
  await app.upsertSkins(account.email, type === 'skin' ? { skin_png: clean, skin_model: model } : { cape_png: clean });
  await app.ensureUuid(account);
  return json(request, 200, { ok: true });
}

