-- Space Client: persistent accounts storage in Supabase
-- Run this once in Supabase Dashboard -> SQL Editor.

create table if not exists public.accounts (
  email text primary key,
  nick text not null,
  nick_normalized text not null unique,
  password_hash text not null,
  balance bigint not null default 0,
  banned boolean not null default false,
  plan text not null default 'none',
  expires timestamptz,
  registered_at timestamptz not null default now(),
  last_seen timestamptz
);

create index if not exists accounts_nick_normalized_idx
  on public.accounts (nick_normalized);

alter table public.accounts enable row level security;

-- The site accesses this table only from the Layero backend with the
-- Supabase secret/service-role key. Do not expose that key in the browser.
revoke all on table public.accounts from anon, authenticated;

comment on table public.accounts is
  'Space Client accounts. Accessed by the Layero backend only.';


-- Compatibility fixes for an existing accounts table:
-- registration must never send NULL into the required plan column.
alter table public.accounts alter column plan set default 'none';
update public.accounts set plan = 'none' where plan is null;
alter table public.accounts alter column plan set not null;

-- Online/offline activity timestamp. Existing accounts start without a last-seen value.
alter table public.accounts add column if not exists last_seen timestamptz;


-- Admin permissions for player management.
alter table public.accounts add column if not exists is_admin boolean not null default false;
update public.accounts set is_admin = true where lower(nick) = 'winzuxx';


-- Persistent sessions: survive Layero runtime restarts/redeploys and browser restarts.
-- The raw session token is never stored in Supabase; only its SHA-256 hash is stored.
create table if not exists public.sessions (
  token_hash text primary key,
  email text not null,
  nick text not null,
  kind text not null check (kind in ('user','admin')),
  created_at timestamptz not null default now()
);

create index if not exists sessions_email_idx on public.sessions (email);
create index if not exists sessions_kind_idx on public.sessions (kind);

alter table public.sessions enable row level security;
revoke all on table public.sessions from anon, authenticated;

comment on table public.sessions is
  'Persistent Space Client sessions. Accessed only by the Layero backend with the Supabase secret/service-role key.';


