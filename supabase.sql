-- Payments / balance top-ups.
-- The Layero backend creates orders and credits balance only after the external
-- payment provider confirms the payment. Card data never touches Space Client.
create table if not exists public.payment_orders (
  order_id text primary key,
  email text not null,
  amount bigint not null check (amount >= 10 and amount <= 1000000),
  currency text not null default 'RUB',
  provider text not null check (provider in ('yookassa','cryptomus')),
  method text not null check (method in ('card','sbp','crypto')),
  provider_payment_id text,
  status text not null default 'pending',
  error_message text,
  credited_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists payment_orders_email_idx on public.payment_orders(email, created_at desc);
create index if not exists payment_orders_provider_id_idx on public.payment_orders(provider, provider_payment_id);
alter table public.payment_orders enable row level security;
revoke all on table public.payment_orders from anon, authenticated;

-- Atomic balance credit used only after a provider has confirmed a payment.
-- This prevents a webhook + status-poll race from crediting the same order twice.
create or replace function public.credit_payment_order(p_order_id text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text;
  v_amount bigint;
  v_credited timestamptz;
  v_balance bigint;
begin
  select email, amount, credited_at
    into v_email, v_amount, v_credited
    from public.payment_orders
   where order_id = p_order_id
   for update;

  if not found then
    raise exception 'Payment order not found';
  end if;

  if v_credited is not null then
    select balance into v_balance from public.accounts where lower(email)=lower(v_email);
    return coalesce(v_balance, 0);
  end if;

  update public.accounts
     set balance = balance + v_amount
   where lower(email)=lower(v_email)
   returning balance into v_balance;

  if not found then
    raise exception 'Account not found';
  end if;

  update public.payment_orders
     set status = 'credited', credited_at = now(), updated_at = now()
   where order_id = p_order_id;

  return v_balance;
end;
$$;

revoke all on function public.credit_payment_order(text) from public;
grant execute on function public.credit_payment_order(text) to service_role;

